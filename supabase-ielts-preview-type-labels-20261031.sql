create or replace function public.ielts_preview_admin_type_labels(
  p_token uuid, p_question_id text default null, p_label text default null
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_admin uuid; v_count integer; v_labels jsonb;
begin
  select s.admin_id into v_admin
  from ielts_preview_private.admin_sessions s
  join ielts_preview_private.admin_accounts a on a.id=s.admin_id
  where s.token_hash=extensions.digest(p_token::text,'sha256')
    and s.expires_at>pg_catalog.clock_timestamp() and a.is_active;
  if v_admin is null then raise exception 'Valid admin sign-in required' using errcode='28000'; end if;
  if p_question_id is not null then
    if p_question_id !~ '^T2-[0-9]{3}$' or substring(p_question_id from 4)::integer not between 1 and 242
       or p_label is null or p_label not in ('Opinions','Discuss both views + Opinions','Advantages & Disadvantages','Cause & Solution','Direct question') then
      raise exception 'Invalid Task 2 classification';
    end if;
    update ielts_preview_private.type_labels
    set label=p_label,updated_at=pg_catalog.clock_timestamp(),updated_by=v_admin
    where question_id=p_question_id;
    get diagnostics v_count=row_count;
    if v_count<>1 then raise exception 'Question label missing'; end if;
  elsif p_label is not null then
    raise exception 'Question ID required';
  end if;
  select coalesce(jsonb_object_agg(question_id,label),'{}'::jsonb) into v_labels
  from ielts_preview_private.type_labels;
  return jsonb_build_object('labels',v_labels,'serverTime',pg_catalog.clock_timestamp());
end; $$;
revoke all on function public.ielts_preview_admin_type_labels(uuid,text,text) from public;
grant execute on function public.ielts_preview_admin_type_labels(uuid,text,text) to anon,authenticated;
