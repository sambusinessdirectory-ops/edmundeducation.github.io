import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(root, "idiom-system-data.js");
const baseSqlPath = path.join(root, "supabase-idiom-system.sql");
const migrationPath = path.join(root, "supabase-idiom-system-lessons-26-138.sql");

function extractFunction(source, functionName) {
  const marker = `create or replace function public.${functionName}(`;
  const start = source.indexOf(marker);
  assert.ok(start >= 0, `Missing SQL function ${functionName}`);
  const end = source.indexOf("\n$$;", start);
  assert.ok(end >= 0, `Unterminated SQL function ${functionName}`);
  return source.slice(start, end + 4);
}

const context = { window: {} };
vm.runInNewContext(fs.readFileSync(dataPath, "utf8"), context, { filename: dataPath });
const data = context.window.EDMUND_IDIOM_SYSTEM_DATA;
assert.equal(data?.system, "idiom");
assert.equal(data.lessonCount, 138);
assert.equal(data.questionCount, 6900);
assert.equal(data.lessons.length, 138);
assert.ok(data.lessons.every((lesson) => lesson.questions.length === 50));

const baseSql = fs.readFileSync(baseSqlPath, "utf8");
assert.match(baseSql, /\^idiom-\(0\[1-9\]\|\[1-9\]\[0-9\]\|1\[0-2\]\[0-9\]\|13\[0-8\]\)\$/);
assert.match(baseSql, /jsonb_array_length\(p_bookmarks\) > 7038/);
assert.match(baseSql, /octet_length\(p_bookmarks::text\) > 1048576/);

const functionNames = [
  "_idiom_system_result_valid",
  "_idiom_system_bookmark_payload_valid",
  "idiom_system_upsert_attempt",
  "idiom_system_list_bookmarks_page",
  "idiom_system_admin_list_bookmarks_page"
];
const functions = functionNames.map((name) => extractFunction(baseSql, name)).join("\n\n");

const migration = `-- Generated by tools/generate-idiom-sql.mjs. Do not edit by hand.
-- Forward-only expansion for existing Idiom System installations.

begin;

set local lock_timeout = '5s';
set local statement_timeout = '2min';

select pg_catalog.pg_advisory_xact_lock(
  pg_catalog.hashtextextended('edmund-idiom-system-lessons-26-138', 0)
);

do $$
begin
  if to_regclass('public.idiom_system_attempts') is null
    or to_regclass('public.idiom_system_bookmarks') is null
  then
    raise exception 'Apply supabase-idiom-system.sql before this expansion';
  end if;
end;
$$;

${functions}

alter table public.idiom_system_bookmarks
  drop constraint if exists idiom_system_bookmarks_lesson_id_check;
alter table public.idiom_system_bookmarks
  add constraint idiom_system_bookmarks_lesson_id_check
  check (lesson_id ~ '^idiom-(0[1-9]|[1-9][0-9]|1[0-2][0-9]|13[0-8])$') not valid;
alter table public.idiom_system_bookmarks
  validate constraint idiom_system_bookmarks_lesson_id_check;

alter table public.idiom_system_bookmarks
  drop constraint if exists idiom_system_bookmarks_check;
alter table public.idiom_system_bookmarks
  drop constraint if exists idiom_system_bookmarks_question_id_check;
alter table public.idiom_system_bookmarks
  add constraint idiom_system_bookmarks_question_id_check
  check (
    (question_id = '__section__' and include_answer = false)
    or question_id ~ ('^' || lesson_id || '-q(0[1-9]|[1-4][0-9]|50)$')
  ) not valid;
alter table public.idiom_system_bookmarks
  validate constraint idiom_system_bookmarks_question_id_check;

alter table public.idiom_system_attempts
  drop constraint if exists idiom_system_attempts_lesson_id_check;
alter table public.idiom_system_attempts
  add constraint idiom_system_attempts_lesson_id_check
  check (lesson_id ~ '^idiom-(0[1-9]|[1-9][0-9]|1[0-2][0-9]|13[0-8])$') not valid;
alter table public.idiom_system_attempts
  validate constraint idiom_system_attempts_lesson_id_check;

revoke all on function public._idiom_system_result_valid(text, jsonb)
  from public, anon, authenticated, service_role;
revoke all on function public._idiom_system_bookmark_payload_valid(jsonb)
  from public, anon, authenticated, service_role;

revoke all on function public.idiom_system_upsert_attempt(
  uuid, uuid, text, text, text, integer, integer, integer, integer,
  timestamptz, jsonb
)
  from public, anon, authenticated, service_role;
revoke all on function public.idiom_system_list_bookmarks_page(uuid, integer, integer)
  from public, anon, authenticated, service_role;
revoke all on function public.idiom_system_admin_list_bookmarks_page(
  uuid, uuid, integer, integer
)
  from public, anon, authenticated, service_role;

grant execute on function public.idiom_system_upsert_attempt(
  uuid, uuid, text, text, text, integer, integer, integer, integer,
  timestamptz, jsonb
)
  to service_role;
grant execute on function public.idiom_system_list_bookmarks_page(uuid, integer, integer)
  to service_role;
grant execute on function public.idiom_system_admin_list_bookmarks_page(
  uuid, uuid, integer, integer
)
  to service_role;

notify pgrst, 'reload schema';

commit;
`;

fs.writeFileSync(migrationPath, migration);
console.log(`Wrote ${path.relative(root, migrationPath)} for ${data.lessonCount} Idiom lessons.`);
