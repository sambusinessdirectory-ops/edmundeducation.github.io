#!/usr/bin/env python3
"""Generate the Common Spelling Traps voice pack with Kokoro af_heart."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

import soundfile as sf
from kokoro_onnx import Kokoro


ROOT = Path(__file__).resolve().parents[1]
MODEL_ROOT = Path("/Volumes/(Pro-G) Sam's Data/CodexData/workspaces/edmund-neural-models")
CATALOG_PATH = ROOT / "spelling-common-traps-catalog.js"
AUDIO_DIR = ROOT / "flashcard-custom-audio/common-spelling-traps"
MANIFEST_PATH = ROOT / "spelling-common-traps-audio-manifest.js"
PUBLIC_PREFIX = "flashcard-custom-audio/common-spelling-traps/"

spec = importlib.util.spec_from_file_location("flashcard_audio", ROOT / "tools/generate-flashcard-audio.py")
helper = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = helper
spec.loader.exec_module(helper)


def normalize(value: str) -> str:
    return re.sub(r"\s+", " ", value.replace("’", "'").replace("‘", "'")).strip().casefold()


def catalog_words() -> list[str]:
    source = CATALOG_PATH.read_text(encoding="utf-8")
    rows = re.findall(r'\["[^"]+","[^"]+","[^"]+","([^"]+)"\]', source)
    words = [word for row in rows for word in row.split("|")]
    return list(dict.fromkeys(words))


def existing_audio() -> dict[str, str]:
    flashcards, _ = helper.load_preserved_manifest(ROOT / "flashcards-audio-manifest.js")
    source = (ROOT / "spelling-jayden-audio-manifest.js").read_text(encoding="utf-8")
    prefix = "window.EDMUND_SPELLING_AUDIO = Object.freeze("
    start = source.index(prefix) + len(prefix)
    spelling, _ = json.JSONDecoder().raw_decode(source[start:])
    combined = {**flashcards, **spelling}
    return {normalize(text): url for text, url in combined.items() if url}


words = catalog_words()
available = existing_audio()
manifest: dict[str, str] = {}
pending: list[tuple[str, str, Path]] = []

for word in words:
    reused = available.get(normalize(word))
    if reused:
        manifest[word] = reused
        continue
    digest = hashlib.sha256(word.encode("utf-8")).hexdigest()[:24]
    output = AUDIO_DIR / f"{digest}.mp3"
    pending.append((word, digest, output))

print(f"Common traps: {len(words)} unique terms; {len(words) - len(pending)} reused; {len(pending)} Kokoro clips", flush=True)
if pending:
    kokoro = Kokoro(str(MODEL_ROOT / "kokoro-v1.0.onnx"), str(MODEL_ROOT / "voices-v1.0.bin"))
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    for number, (word, digest, output) in enumerate(pending, 1):
        if not helper.valid_existing_audio(output):
            samples, rate = kokoro.create(helper.spoken_text(word), voice="af_heart", lang="en-us", speed=0.96)
            sf.write(output, samples, rate, format="MP3", subtype="MPEG_LAYER_III",
                     compression_level=0.55, bitrate_mode="VARIABLE")
        if not helper.valid_existing_audio(output):
            raise RuntimeError(f"Invalid Kokoro audio: {word}")
        manifest[word] = PUBLIC_PREFIX + digest + ".mp3"
        print(f"{number}/{len(pending)} {word}", flush=True)

ordered = {word: manifest[word] for word in words}
MANIFEST_PATH.write_text(
    "/* Generated by tools/generate-common-spelling-traps-audio.py. */\n"
    "window.EDMUND_COMMON_TRAPS_AUDIO = Object.freeze("
    + json.dumps(ordered, ensure_ascii=False, separators=(",", ":"))
    + ");\n"
    "window.EDMUND_COMMON_TRAPS_AUDIO_META = Object.freeze("
    + json.dumps({
        "engine": "Kokoro-82M", "voice": "af_heart", "language": "en-us",
        "speed": 0.96, "count": len(ordered), "generatedCount": len(pending),
        "format": "audio/mpeg"
    }, separators=(",", ":"))
    + ");\n",
    encoding="utf-8",
)
print(f"Wrote {MANIFEST_PATH.name} with {len(ordered)} mappings", flush=True)
