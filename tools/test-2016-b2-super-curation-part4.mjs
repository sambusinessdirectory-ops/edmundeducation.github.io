import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import zlib from 'node:zlib';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dataSource=fs.readFileSync(path.join(root,'tools/paper3/2016-b2/source/super-curation-stage4-data.js'),'utf8');
const sandbox={window:{}};vm.runInNewContext(dataSource,sandbox);
const data=sandbox.window.EDMUND_2016_B2_CURATION_STAGE4;
const controller=fs.readFileSync(path.join(root,'tools/paper3/2016-b2/source/super-curation-stage4.js'),'utf8');
const css=fs.readFileSync(path.join(root,'paper3/2016-b2/super-curation.css'),'utf8');
const html=fs.readFileSync(path.join(root,'paper3/2016-b2/index.html'),'utf8');
const generated=JSON.parse(fs.readFileSync(path.join(root,'tools/paper3/2016-b2/audit/stage4-factline-records.json'),'utf8'));
const runtime=zlib.gunzipSync(fs.readFileSync(path.join(root,'paper3/2016-b2/stage4-runtime.js.gz'))).toString('utf8');

assert.equal(data.version,'2016-b2-super-curation-stage4-v1');
assert.equal(data.records.length,148);
assert.equal(new Set(data.records.map(record=>record.id)).size,148);
assert.deepEqual(Array.from(new Set(data.records.map(record=>record.page))),[4,5,6,7,8,9,10]);
assert.deepEqual(Array.from(data.excludedBlocks),[1,8,9,10]);
assert.equal(data.records.every(record=>record.translation&&record.typeLabel&&record.decision&&Object.values(record.analysis).every(Boolean)),true);
assert.equal(data.records.filter(record=>record.visual).length,3);
assert.equal(data.records.filter(record=>record.bankEligible).length,37);
assert.equal(data.records.some(record=>/Lara Gau to Indy Wong/.test(record.excerpt)),false,'boss letter is excluded from Stage 4');
assert.equal(data.records.some(record=>/Nosing Around/.test(record.excerpt)),false,'podcast is excluded from Stage 4');
assert.equal(JSON.stringify(generated.records.map(record=>record.id)),JSON.stringify(Array.from(data.records,record=>record.id)));
assert.match(controller,/CSS\.highlights/);
assert.match(controller,/prefers-reduced-motion/);
assert.match(controller,/setTimeout\(cancelFlight,900\)/);
assert.match(controller,/Stage 5 保持未開放/);
assert.match(controller,/classificationRevisions/);
assert.match(controller,/exact-phrase-missing/);
assert.match(controller,/curation-stage4-search/);
assert.doesNotMatch(controller,/你會先標哪個任務/);
assert.match(css,/::highlight\(stage4-a\)/);
assert.match(css,/curation-stage4-file-stamp/);
assert.match(css,/curation-stage4-bank/);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(html,/super-curation-stage4-loader\.js\?v=20261128-stage4-v1/);
assert.match(runtime,/EDMUND_2016_B2_CURATION_STAGE4_DEBUG/);
console.log(`2016 B2 Super Curation Part 4 static contract: PASS (${data.records.length} records; ${data.records.filter(record=>record.bankEligible).length} bank entries)`);
