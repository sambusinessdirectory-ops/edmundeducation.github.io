import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {prepareTranslation} from './dse-reading-translations.mjs';
const root=new URL('../',import.meta.url);
const read=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
const data=await read('dse-reading-data/dse-2024-b1.json');
assert.equal(data.paragraphs.length,14);
assert.deepEqual(data.paragraphs.map(p=>p.number),Array.from({length:14},(_,i)=>i+1));
assert.ok(data.paragraphs.slice(0,7).every(p=>p.label.startsWith('Text 3')));
assert.ok(data.paragraphs.slice(7).every(p=>p.label.startsWith('Text 4')));
assert.match(data.paragraphs[1].text,/HK\$50/);
assert.match(data.paragraphs[9].text,/on-street hawking activities as unfair competition/);
assert.match(data.paragraphs[13].text,/society would be quiet and empty/);
assert.ok(data.paragraphs.every(p=>!p.text.includes('END OF READING')&&!p.text.includes('Marking Schemes')));
assert.deepEqual(data.questions.map(q=>q.number),Array.from({length:19},(_,i)=>i+24));
assert.equal(data.questions.reduce((n,q)=>n+(q.parts?.length||1),0),42);
const q=n=>data.questions.find(q=>q.number===n);
for(const [n,count] of [[31,3],[34,4],[35,3],[36,6],[37,3],[38,3],[40,3],[41,6]])assert.equal(q(n).parts.length,count);
for(const n of [26,29,32])assert.deepEqual(q(n).options.map(o=>o.value),['A','B','C','D']);
for(const n of [34,38])q(n).parts.forEach(p=>assert.deepEqual(p.options,['T','F','NG']));
assert.ok(q(36).tables[0].flow);
assert.equal(q(36).tables[0].rows.filter(r=>r[0].text==='↓').length,2);
assert.equal(q(40).tables[0].rows[1][1].text,'E (example)');
q(40).parts.forEach(p=>assert.deepEqual(p.options,['A','B','C','D']));
assert.equal(q(41).tables[0].rows[2][1].text,'D (example)');
q(41).parts.forEach(p=>assert.deepEqual(p.options,['A','B','C','E','F','G']));
for(const figure of [...data.paragraphs.flatMap(p=>p.images||[]),...q(40).figures])assert.ok((await readFile(new URL(figure.src,root))).length>1000);
const row=prepareTranslation(data,await read('tools/dse-reading-translations/dse-2024-b1.json'));
assert.equal(row.content.entries.filter(e=>/^paragraphs\/\d+\/text$/.test(e.path)).length,14);
assert.ok(data.questions.every(q=>!('answer' in q)));
const year=(await read('dse-reading-catalogue.json')).years.find(y=>y.year===2024);
assert.equal(year.sections.B1.id,data.id);assert.equal(year.sections.B2.id,'dse-2024-b2');assert.equal(year.sections.A,null);
console.log('DSE 2024 B1: both texts, 19 questions, 42 answer fields, original photographs, flow sequence, matching examples and complete translations verified.');
