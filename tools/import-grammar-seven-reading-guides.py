#!/usr/bin/env python3
"""Import seven reviewed DOCX Grammar reading guides into canonical Markdown."""

from __future__ import annotations

import hashlib
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "course-materials/grammar/source"
DOWNLOADS = Path("/Users/sammak/Downloads")


def load(path: Path):
    spec = importlib.util.spec_from_file_location("grammar_import_shared", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(module)
    return module


shared = load(ROOT / "tools/import-grammar-seventeen-reading-guides.py")
GUIDES = (
    ("nominalisation", "NOM", 327, "Nominalisation", "名詞化", "Nominalisation — All Forms Complete Student Reading Guide.docx"),
    ("linking-verbs", "LV", 213, "Linking Verbs", "連繫動詞", "Linking Verbs — Complete Student Reading Guide (213 Rules).docx"),
    ("english-prefixes", "PX", 271, "English Prefixes", "英文前綴與相關字首", "English Prefixes — Complete Student Reading Guide (271 lessons).docx"),
    ("quantifiers", "QNT", 396, "Quantifiers", "數量詞與數量結構", "Quantifiers — Complete Student Reading Guide (396 Lessons).docx"),
    ("english-suffixes", "SUF", 327, "English Suffixes", "英文詞尾", "English Suffixes — Complete Student Reading Guide Common to Advanced.docx"),
    ("phrase-types", "PHR", 288, "Different Types of Phrases", "各類詞組", "Different Types of Phrases — Complete Student Reading Guide (288 Rules).docx"),
    ("nouns-noun-phrases", "NN", 248, "Nouns, Noun Phrases & Nominal Constructions", "名詞、名詞短語與名詞結構", "Nouns, Noun Phrases & Nominal Constructions — Student Reading Guide (248 lessons).docx"),
)


def main() -> None:
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    for slug, prefix, count, _english, _chinese, filename in GUIDES:
        source = DOWNLOADS / filename
        body = shared.import_docx(source, prefix)
        header = (
            "<!-- Generated by tools/import-grammar-seven-reading-guides.py. -->\n"
            f"<!-- Source: {source.name}; SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()} -->\n\n"
        )
        content = header + body
        shared.validate(content, prefix, count, source)
        output = SOURCE_DIR / f"{slug}-student-reading-guide-{count}.md"
        output.write_text(content, encoding="utf-8")
        print(f"Imported {count:>3} rules: {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
