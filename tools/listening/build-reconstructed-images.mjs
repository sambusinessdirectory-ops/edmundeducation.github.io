// Packages already-reviewed built-in ImageGen outputs. Does not call an image API.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { dseImageSources, root } from './image-sources.mjs';

const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || 'sharp');
const generatedRoot = process.argv[2];
const plan = JSON.parse(fs.readFileSync(path.join(root, 'tools/listening/reconstruction-prompts.json')));
const outputRoot = 'assets/dse-listening/reconstructed-v3';
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const manifest = { version: 3, method: 'User-authorized AI reference reconstruction using the built-in image tool. Fine details are reconstructed, not recovered historical pixels. Original files are preserved. Responsive WebP derivatives use proportional resizing with white padding, never stretching or cropping.', images: {} };

for (const source of dseImageSources()) {
  const record = plan.images[source];
  if (!record?.reviewed) throw new Error('Unreviewed reconstruction: ' + source);
  const master = `${outputRoot}/${record.id}-master.png`;
  fs.mkdirSync(path.dirname(path.join(root, master)), { recursive: true });
  if (generatedRoot) fs.copyFileSync(path.join(generatedRoot, record.generatedFile), path.join(root, master));
  const original = fs.readFileSync(path.join(root, source));
  const originalMeta = await sharp(original).metadata();
  const masterBytes = fs.readFileSync(path.join(root, master));
  const masterMeta = await sharp(masterBytes).metadata();
  const entry = {
    sourceSha256: hash(original), sourceWidth: originalMeta.width, sourceHeight: originalMeta.height,
    profile: 'reviewed-reference-reconstruction',
    restorationInput: { kind: 'authorized-ai-reconstruction', reference: record.reference, promptRecord: 'tools/listening/reconstruction-prompts.json', master: { src: master, width: masterMeta.width, height: masterMeta.height, sha256: hash(masterBytes) } },
  };
  for (const [label, edge, quality] of [['small', 640, 88], ['preview', 1280, 92], ['full', 3840, 94]]) {
    const width = Math.round(originalMeta.width * edge / Math.max(originalMeta.width, originalMeta.height));
    const height = Math.round(originalMeta.height * edge / Math.max(originalMeta.width, originalMeta.height));
    const src = `${outputRoot}/${record.id}-${edge}.webp`;
    await sharp(masterBytes).resize(width, height, { fit: 'contain', background: '#ffffff', kernel: 'lanczos3' }).webp({ quality, effort: 6 }).toFile(path.join(root, src));
    entry[label] = { src, width, height, bytes: fs.statSync(path.join(root, src)).size };
  }
  manifest.images[source] = entry;
  console.log('Packaged ' + record.id);
}
fs.writeFileSync(path.join(root, outputRoot, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'dse-listening-image-manifest.mjs'), '// Generated by tools/listening/build-reconstructed-images.mjs; originals remain untouched.\nexport const DSE_IMAGE_ENHANCEMENTS = ' + JSON.stringify(manifest.images, null, 2) + ';\n');
console.log(`Packaged ${Object.keys(manifest.images).length} reviewed reconstructions.`);
