#!/usr/bin/env node
// Keep legacy question IDs for past events; append separate v2 IDs for new runs.
import {writeFile} from 'node:fs/promises';
import {plan} from './plan-native-english-redesign.mjs';
import {editorialIssues} from './test-native-editorial-quality.mjs';

const rows=plan().rows;
const missing=rows.filter(row=>row.status!=='draft-needs-editorial-review');
if(missing.length||editorialIssues.length){
  console.error(`BLOCKED: ${missing.length} missing lessons; ${editorialIssues.length} editorial issues.`);
  process.exit(1);
}

const used=new Set();
const statements=[];
for(const row of rows){
  const lesson=(await import(new URL(`../natural-english/lesson-${String(row.number).padStart(3,'0')}.mjs`,import.meta.url))).default;
  const catalogue={};
  for(const q of lesson.questions){
    if(used.has(q.id))throw new Error(`Duplicate question ID: ${q.id}`);
    used.add(q.id);
    catalogue[q.id]={type:q.type,answers:q.answers,options:q.type==='mc'?q.options:[]};
  }
  const json=JSON.stringify(catalogue).replaceAll("'","''");
  statements.push(`update natural_english_private.catalogue set questions=questions || '${json}'::jsonb where module='${row.id}';`);
}
const output=new URL('../supabase/migrations/20260929050000_native_english_redesign_catalogue.sql',import.meta.url);
const source=`-- Generated by tools/build-native-editorial-catalogue-migration.mjs.\n-- Separate v2 question IDs keep old practice history intact.\n${statements.join('\n')}\n`;
await writeFile(output,source);
console.log(`Built ${statements.length} catalogue updates for ${used.size} v2 questions (${Buffer.byteLength(source)} bytes).`);
