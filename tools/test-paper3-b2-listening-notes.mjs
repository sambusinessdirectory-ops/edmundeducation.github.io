import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const base='paper3/2025-b2/';
const html=fs.readFileSync(base+'index.html','utf8');
assert(html.indexOf('sentence-analysis.js?')<html.indexOf('listening-notes.js?'));
assert(html.includes('listening-notes.css?'));
assert(fs.statSync(base+'part-b-meeting.m4a').size>1000000);
const provenance=JSON.parse(fs.readFileSync(base+'recording-provenance.json','utf8'));
assert.equal(provenance.meetingCutDurationSeconds,517.5);
if(process.env.PAPER3_DOM_TEST_MODULE){
  const {JSDOM}=require(process.env.PAPER3_DOM_TEST_MODULE);
  const dom=new JSDOM(html,{url:'https://edmundeducation.com/paper3/2025-b2/',runScripts:'outside-only'});
  const {window}=dom, doc=window.document;
  let playCount=0;
  window.HTMLMediaElement.prototype.play=function(){playCount++;return Promise.resolve();};
  const fields=[...doc.querySelectorAll('[data-save]')];
  fields.filter(f=>f.tagName==='TEXTAREA').forEach(f=>f.value='Existing student notes');
  const original=[...doc.querySelectorAll('.recording-script .speech')].map(s=>s.outerHTML);
  for(const file of ['sentence-analysis-core.js','sentence-analysis-data.js','sentence-analysis.js','listening-notes.js'])window.eval(fs.readFileSync(base+file,'utf8'));
  const panels=[...doc.querySelectorAll('.notes-evidence')];
  const audio=doc.querySelector('#page-3 audio');
  Object.defineProperty(audio,'readyState',{value:1,configurable:true});
  assert(audio.controls);
  assert.equal(audio.preload,'metadata');
  assert.equal(audio.autoplay,false);
  assert.equal(audio.getAttribute('src'),'/paper3/2025-b2/part-b-meeting.m4a');
  assert.equal(doc.querySelector('#page-3 .source-paper').firstElementChild.className,'notes-audio');
  audio.dispatchEvent(new window.Event('error'));
  assert(doc.querySelector('.notes-audio-status').textContent.includes('重試'));
  assert.equal(doc.querySelector('.notes-audio-retry').hidden,false);
  audio.dispatchEvent(new window.Event('loadedmetadata'));
  assert.equal(doc.querySelector('.notes-audio-status').textContent,'');
  assert.equal(panels.length,6);
  assert.equal(doc.querySelectorAll('.sentence-item').length,257,'The excerpt copies must not be annotated as new Data File sentences');
  for(const panel of panels){
    assert.equal(panel.open,false,'Answers start hidden');
    assert.equal(panel.nextElementSibling.id,'notes-'+panel.dataset.notesSection);
    assert(panel.querySelectorAll('.speech').length>0);
    assert.equal(panel.querySelectorAll('a').length,0,'No navigation is needed for evidence');
    const play=panel.querySelector('.notes-section-play');
    play.click();
    assert.equal(audio.currentTime,provenance.sectionStartsSeconds[panel.dataset.notesSection]);
    assert(audio.currentTime<provenance.meetingCutDurationSeconds);
    panel.open=true;panel.dispatchEvent(new window.Event('toggle'));
    assert.equal(panel.querySelector('summary').textContent,'收起相關錄音內容');
    panel.open=false;panel.dispatchEvent(new window.Event('toggle'));
    assert.equal(panel.querySelector('summary').textContent,'顯示相關錄音內容');
  }
  assert.equal(playCount,6);
  Object.defineProperty(audio,'readyState',{value:0,configurable:true});
  panels[0].querySelector('.notes-section-play').click();
  audio.dispatchEvent(new window.Event('loadedmetadata'));
  assert.equal(audio.currentTime,20.3,'Seeking before metadata is ready is applied once loaded');
  assert.deepEqual([...doc.querySelectorAll('.recording-script .speech')].map(s=>s.outerHTML),original);
  assert.deepEqual([...doc.querySelectorAll('[data-save]')],fields);
  fields.filter(f=>f.tagName==='TEXTAREA').forEach(f=>assert.equal(f.value,'Existing student notes'));
  const text=id=>doc.querySelector(`[data-notes-section="${id}"]`).textContent;
  assert.match(text('slogan'),/One Games, One Asia/);
  assert.match(text('opening'),/13th of October/);
  assert.match(text('opening'),/Main Hall/);
  assert.match(text('wellness'),/Relax and Recover/);
  assert.match(text('wellness'),/two famous instructors/);
  assert.match(text('parents'),/school website/);
  assert.match(text('parents'),/No, through the school app/);
  assert.match(text('parents'),/briefing session/);
  assert.match(text('topic'),/why they think their sport should be added/);
  assert.match(text('after'),/time for students to ask questions/);
  console.log('Listening notes: six independent in-page transcript toggles; corrections, saved notes and original transcript preserved.');
  window.close();
}
