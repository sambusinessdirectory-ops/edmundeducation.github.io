import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(new URL('./email-qa/package.json',import.meta.url));
const {JSDOM}=require('jsdom');
const catalog=JSON.parse(await fs.readFile(new URL('../system-access-catalog.json',import.meta.url),'utf8'));
assert.equal(catalog.length,62);assert.ok(catalog.reduce((n,s)=>n+s.children.length,0)>5000);
const dom=new JSDOM('<section id="access"></section>',{url:'https://edmundeducation.com/schedule-system.html'});
const w=dom.window,root=w.document.querySelector('section');let saved;
const source=(await fs.readFile(new URL('../system-access-admin.mjs',import.meta.url),'utf8')).replace(/^import [^;]+;/,'').replaceAll('export ','');
const ctx=vm.createContext({document:w.document,fetch:async()=>({ok:true,json:async()=>catalog}),e:s=>String(s).replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;')});
vm.runInContext(source+';globalThis.mount=mountSystemAccess;',ctx);
await ctx.mount(root,{id:'test',access:{}},a=>saved=a);
assert.equal(root.querySelectorAll('details').length,62);
const search=root.querySelector('[type=search]');search.value='Listening';search.dispatchEvent(new w.Event('input'));
assert.ok(root.querySelectorAll('details').length<62);
const cb=root.querySelector('[data-unified-key^="system:"]');cb.checked=false;cb.dispatchEvent(new w.Event('change',{bubbles:true}));assert.equal(saved[cb.dataset.unifiedKey],false);
await ctx.mount(root,{id:'test',access:saved},a=>saved=a);assert.equal(root.querySelector('[data-unified-key^="system:"]').checked,false);
w.close();console.log('All 62 systems: searchable access controls, subsection catalog and saved toggles passed.');
