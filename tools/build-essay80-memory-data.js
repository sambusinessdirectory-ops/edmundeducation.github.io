// Regenerate the compact pilot data from writing-practice's canonical essay and audio manifest.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const context = { window: {} };
for (const file of ['writing-practice-model-essays-53-96-data.js', 'writing-audio-manifest.js']) {
  vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
}

const id = 'model-essay-80-ielts-opinion';
const essay = context.window.EDMUND_IELTS_WRITING_53_96_EXERCISES[id];
const audio = context.window.EDMUND_WRITING_AUDIO[id];
if (!essay || !audio?.path || !Array.isArray(audio.words)) throw new Error('Essay 80 source or audio is missing');

const tokenize = text => [...text.matchAll(/[\p{L}\p{N}]+(?:[-’'][\p{L}\p{N}]+)*/gu)].map(match => match[0]);
const sourceSentences = essay.translationSections.flatMap((section, paragraph) =>
  section.items.map((item, index) => ({
    paragraph,
    index,
    role: item.label,
    english: item.english,
    chinese: item.chinese,
  }))
);
const tokens = sourceSentences.flatMap(sentence => tokenize(sentence.english));
if (tokens.length !== audio.words.length || tokens.some((word, index) => word !== audio.words[index][0])) {
  throw new Error('Essay 80 narration no longer matches the canonical sentence text');
}
let cursor = 0;
const sentences = sourceSentences.map(sentence => {
  const count = tokenize(sentence.english).length;
  const first = audio.words[cursor];
  const last = audio.words[cursor + count - 1];
  const next = audio.words[cursor + count];
  cursor += count;
  return {
    ...sentence,
    words: audio.words.slice(cursor - count, cursor),
    start: Math.max(0, first[1] - 0.16),
    end: next ? Math.max(last[2], next[1] - 0.08) : last[2] + 0.4,
  };
});

const data = {
  id,
  title: essay.title,
  question: essay.questionPrompt,
  audio: audio.path,
  sentences,
  mediumAnswers: essay.practiceDifficultySets.find(set => set.key === "medium").answers,
};
fs.writeFileSync(path.join(root, 'essay-80-memory-data.js'),
  `/* Generated by tools/build-essay80-memory-data.js from writing-practice source. */\nwindow.ESSAY_80_MEMORY_DATA = ${JSON.stringify(data, null, 2)};\n`);
