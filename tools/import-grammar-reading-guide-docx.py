def normalize(value: str) -> str:
    return "\n".join(line.rstrip() for line in value.replace("\r", "").splitlines()).strip()


def rewrite_prohibited_wording(value: str) -> str:
    value = normalize(value)
    for old, new in PROHIBITED_REWRITES.items():
        value = value.replace(old, new)
    return value


def table_to_markdown(table: Table) -> list[str]:
    rows = []
    for row in table.rows:
        cells = [rewrite_prohibited_wording(cell.text).replace("\n", "<br>") for cell in row.cells]
        rows.append(cells)
    if not rows:
        return []
    width = max(map(len, rows))
    rows = [row + [""] * (width - len(row)) for row in rows]
    escape = lambda value: value.replace("|", "\\|")
    return [
        "| " + " | ".join(map(escape, rows[0])) + " |",
        "| " + " | ".join("---" for _ in range(width)) + " |",
        *("| " + " | ".join(map(escape, row)) + " |" for row in rows[1:]),
    ]


def paragraph_to_markdown(text: str, part: str, config: dict) -> str:
    text = rewrite_prohibited_wording(text)
    if not text:
        return ""
    if text == config["title"] or text.startswith("PART "):
        return f"# {text}"
    if text in STEP_LABELS:
        return f"**{text}**"
    rule_re = re.compile(rf"^{config['prefix']}\.\d{{2}}\.\d{{2}}\s+[—-]\s+.+")
    if part.startswith("PART III") and rule_re.match(text):
        return f"### {text}"
    if FAMILY_RE.match(text) or SUBHEADING_RE.match(text):
        return f"## {text}"
    return text


def extract(source: Path, config: dict) -> str:
    document = Document(source)
    output = [
        "<!-- Generated by tools/import-grammar-reading-guide-docx.py. -->",
        f"<!-- Source: {source.name}; SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()} -->",
        "",
    ]
    current_part = ""
    table_count = 0
    for block in iter_blocks(document):
        if isinstance(block, Paragraph):
            text = normalize(block.text)
            if text.startswith("PART "):
                current_part = text
            output.append(paragraph_to_markdown(text, current_part, config))
        else:
            table_count += 1
            output.extend(table_to_markdown(block))
        output.append("")
    result = "\n".join(output).rstrip() + "\n"

    part3 = result.index("# PART III")
    part4 = result.index("# PART IV", part3)
    rule_pattern = rf"^###\s+({config['prefix']}\.\d{{2}}\.\d{{2}})\s+[—-]\s+.+$"
    rules = re.findall(rule_pattern, result[part3:part4], re.M)
    if len(rules) != config["count"] or len(set(rules)) != config["count"]:
        raise ValueError(f"Expected {config['count']} unique Part III rules; found {len(rules)}")
    for label in STEP_LABELS:
        count = len(re.findall(rf"^\*\*{re.escape(label)}\*\*$", result[part3:part4], re.M))
        if count != config["count"]:
            raise ValueError(f"Expected {config['count']} occurrences of {label}; found {count}")
    if result.count("\n# PART ") != 10:
        raise ValueError("Expected all ten authored parts")
    if table_count != config["tables"]:
        raise ValueError(f"Expected {config['tables']} authored tables; found {table_count}")
    if "而是" in result:
        raise ValueError("Prohibited Chinese sentence structure remains in the extracted guide")
    if "jayden" in result.lower():
        raise ValueError("Unexpected personal name remains in the extracted guide")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("slug", choices=GUIDES)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    config = GUIDES[args.slug]
    output = args.output or ROOT / "course-materials/grammar/source" / config["output"]
    content = extract(args.source, config)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"Extracted {config['count']} {args.slug} rules to {output}")


if __name__ == "__main__":
    main()
