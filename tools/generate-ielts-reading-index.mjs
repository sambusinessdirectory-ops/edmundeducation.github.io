#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const toolsDirectory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(toolsDirectory, "..");
const outputArgument = process.argv.indexOf("--output");
const outputPath = outputArgument >= 0 && process.argv[outputArgument + 1]
  ? path.resolve(process.cwd(), process.argv[outputArgument + 1])
  : path.join(root, "flashcards-ielts-reading-index.js");

const html = await readFile(path.join(root, "flashcards.html"), "utf8");
const assignmentStart = html.indexOf("window.EDMUND_FLASHCARD_SEED = {");
const assignmentEnd = html.indexOf("\n  </script>", assignmentStart);
if (assignmentStart < 0 || assignmentEnd < 0) {
  throw new Error("Could not locate the inline flashcard seed");
}

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(html.slice(assignmentStart, assignmentEnd), sandbox, {
  filename: "flashcards.html#EDMUND_FLASHCARD_SEED",
  timeout: 20_000
});

for (const passage of [1, 2, 3]) {
  const file = `flashcards-ielts-reading-passage-${passage}-data.js`;
  const source = await readFile(path.join(root, file), "utf8");
  vm.runInContext(source, sandbox, { filename: file, timeout: 20_000 });
}

const practiceOneTitles = {
  1: "Andrea Palladio - Italian Architect",
  2: "Such a Fascinating Game",
  3: "ARE WE MANAGING TO DESTROY SCIENCE?"
};
const index = {};
for (const passage of [1, 2, 3]) {
  const prefix = `ielts/reading/passage-${passage}/`;
  const titleMap = sandbox.window[`EDMUND_IELTS_READING_PASSAGE_${passage}_TITLES`] || {};
  const rows = Object.entries(sandbox.window.EDMUND_FLASHCARD_SEED || {})
    .filter(([deckId, cards]) => deckId.startsWith(prefix) && Array.isArray(cards) && cards.length > 0)
    .map(([deckId, cards]) => {
      const practice = deckId.slice(prefix.length);
      const ordinal = Number(/^Practice (\d+)$/.exec(practice)?.[1]);
      if (!Number.isSafeInteger(ordinal) || ordinal < 1) {
        throw new Error(`Invalid IELTS Reading deck id: ${deckId}`);
      }
      const title = ordinal === 1 ? practiceOneTitles[passage] : titleMap[practice];
      if (!title) throw new Error(`Missing title for ${deckId}`);
      return { practice, ordinal, title, cardCount: cards.length };
    })
    .sort((left, right) => left.ordinal - right.ordinal);
  index[`Passage ${passage}`] = rows;
}

const generated = "// Generated by tools/generate-ielts-reading-index.mjs. Do not edit by hand.\n" +
  `window.EDMUND_IELTS_READING_INDEX = Object.freeze(${JSON.stringify(index)});\n`;
await writeFile(outputPath, generated, "utf8");
console.log(`Wrote ${Object.values(index).reduce((sum, rows) => sum + rows.length, 0)} IELTS Reading deck summaries to ${path.relative(process.cwd(), outputPath) || outputPath}`);
