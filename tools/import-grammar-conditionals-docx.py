#!/usr/bin/env python3
"""Extract the reviewed Conditionals DOCX into the canonical grammar source."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from docx import Document
from docx.document import Document as DocumentObject
from docx.table import Table
from docx.text.paragraph import Paragraph

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "course-materials/grammar/source/conditionals-student-reading-guide-298.md"
RULE_RE = re.compile(r"^CD\.\d{2}\.\d{2}\s+—\s+.+")
FAMILY_RE = re.compile(r"^\d{2}｜.+")
SUBHEADING_RE = re.compile(r"^(?:[IVX]+|\d+)\.\d+(?:\.\d+)?\s+.+")
STEP_LABELS = (
    "① 先明白意思",
    "② 看英文例句",
    "③ 看中文意思",
    "④ 看為甚麼這樣寫",
    "⑤ 比較接近的寫法",
    "⑥ 最後看限制或例外",
)


def iter_blocks(parent: DocumentObject):
    """Yield paragraphs and tables in their authored XML order."""
    for child in parent.element.body.iterchildren():
        if child.tag.endswith("}p"):
            yield Paragraph(child, parent)
        elif child.tag.endswith("}tbl"):
            yield Table(child, parent)


def rewrite_prohibited_wording(value: str) -> str:
    """Keep the established Chinese style restriction in generated student content."""
    replacements = {
        "說話者不是真的變成對方，而是在提出意見。": "說話者沒有真的變成對方；這句是在提出意見。",
        "有時 if not 不是說事情真的沒有發生，而是在修正程度。": "有時 if not 沒有表示事情真的未發生，重點在修正程度。",
    }
    for old, new in replacements.items():
        value = value.replace(old, new)
    return value


def table_to_markdown(table: Table) -> list[str]:
    rows = []
    for row in table.rows:
        cells = [rewrite_prohibited_wording(" ".join(cell.text.split())) for cell in row.cells]
        rows.append(cells)
    if not rows:
        return []
    width = max(map(len, rows))
    rows = [row + [""] * (width - len(row)) for row in rows]
    escape = lambda value: value.replace("|", "\\|")
    return [
        "| " + " | ".join(map(escape, rows[0])) + " |",
        "| " + " | ".join("---" for _ in range(width)) + " |",
        *("| " + " | ".join(map(escape, row)) + " |" for row in rows[1:]),
    ]


def paragraph_to_markdown(text: str, part: str) -> str:
    text = rewrite_prohibited_wording(text.strip())
    if not text:
        return ""
    if text.startswith("PART "):
        return f"# {text}"
    if text == "Conditionals｜英文條件句完整學習指南":
        return f"# {text}"
    if text in STEP_LABELS:
        return f"**{text}**"
    if part.startswith("PART III") and RULE_RE.match(text):
        return f"### {text}"
    if FAMILY_RE.match(text):
        return f"## {text}"
    if SUBHEADING_RE.match(text):
        return f"## {text}"
    return text


def extract(source: Path) -> str:
    document = Document(source)
    output = [
        "<!-- Generated by tools/import-grammar-conditionals-docx.py. -->",
        f"<!-- Source: {source.name}; SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()} -->",
        "",
    ]
    current_part = ""
    for block in iter_blocks(document):
        if isinstance(block, Paragraph):
            text = block.text.strip()
            if text.startswith("PART "):
                current_part = text
            output.append(paragraph_to_markdown(text, current_part))
        else:
            output.extend(table_to_markdown(block))
        output.append("")
    result = "\n".join(output).rstrip() + "\n"

    part3 = result.index("# PART III")
    part4 = result.index("# PART IV", part3)
    rules = re.findall(r"^###\s+(CD\.\d{2}\.\d{2})\s+—\s+.+$", result[part3:part4], re.M)
    if len(rules) != 298 or len(set(rules)) != 298:
        raise ValueError(f"Expected 298 unique Part III rules; found {len(rules)}")
    for label in STEP_LABELS:
        count = len(re.findall(rf"^\*\*{re.escape(label)}\*\*$", result[part3:part4], re.M))
        if count != 298:
            raise ValueError(f"Expected 298 occurrences of {label}; found {count}")
    if result.count("\n# PART ") != 10:
        raise ValueError("Expected all ten authored parts")
    if result.count("\n| ---") != 11:
        raise ValueError("Expected all eleven authored tables")
    if "而是" in result:
        raise ValueError("Prohibited Chinese sentence structure remains in the extracted guide")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    content = extract(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Extracted 298 Conditionals rules to {args.output}")


if __name__ == "__main__":
    main()
