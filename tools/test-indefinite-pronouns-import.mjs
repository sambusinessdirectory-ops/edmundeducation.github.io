import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from '/Users/sammak/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';

const manifest = JSON.parse(fs.readFileSync('tools/indefinite-pronouns-import-manifest.json'));
assert.equal(manifest.guideConcepts, 68);
assert.equal(manifest.exercises, 250);
assert.equal(manifest.proofreadingPassages, 10);
assert.equal(manifest.proofreadingQuestions, 200);
assert.equal(manifest.answerKeySupplied, false);
const browser = await chromium.launch();
const errors = [];
const page = await browser.newPage({ viewport: { width: 1220, height: 900 } });
page.on('pageerror', error => errors.push(error.message));
const emptyPage = '<!doctype html><html><head></head><body><div data-learning-portal-root><div data-view="dashboard"><div data-grammar-library></div></div></div></body></html>';
await page.route('**/grammar-test.html', route => route.fulfill({ contentType: 'text/html', body: emptyPage }));
await page.goto('http://127.0.0.1:8633/grammar-test.html');
for (const file of ['grammar-system.css','grammar-indefinite-pronouns.css']) await page.addStyleTag({path:file});
await page.evaluate(() => { window.EDMUND_LEARNING_PORTAL_CONTEXT = { getSession: () => ({user: {id: 'qa-grammar'}}) }; });
for (const file of ['grammar-new-curations-data.js','grammar-indefinite-pronouns-data.js','grammar-new-curations.js','grammar-indefinite-pronouns.js']) await page.addScriptTag({path: file});
assert.equal(await page.locator('.grammar-lesson-card--new-curation').count(), 4);
assert.equal(await page.locator('[data-new-grammar-curation="indefinite-pronouns"] .grammar-new-topic[id*="topic-IP"]').count(), 68);
assert.equal(await page.locator('[data-new-grammar-curation="indefinite-pronouns"] .grammar-new-chapters a').count(), manifest.guideChapters);
await page.locator('.grammar-lesson-card--new-curation').last().getByText('開始 250 題練習').click();
assert.equal(await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-number]').innerText(), '第 1 / 250 題');
await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-answer]').fill('someone');
await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-finish]').click();
assert.equal(await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-count]').innerText(), '1');
await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-range]').selectOption('226');
await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-go="250"]').click();
assert.equal(await page.locator('[data-new-grammar-practice="indefinite-pronouns"] [data-number]').innerText(), '第 250 / 250 題');
assert(await page.evaluate(() => JSON.parse(localStorage.getItem('edmund-grammar-indefinite-250-v1:qa-grammar')).done['1']));
await page.setViewportSize({width:390,height:844});
assert(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Grammar mobile horizontal overflow');

const errorPage = await browser.newPage({viewport:{width:1220,height:900}});
errorPage.on('pageerror', error => errors.push(error.message));
await errorPage.route('**/error-test.html', route => route.fulfill({contentType:'text/html',body:'<!doctype html><html><head></head><body><div data-view="dashboard"><section data-error-id-modes><div class="error-id-mode-grid"><button class="error-id-mode-card">Single</button><button class="error-id-mode-card">Passage</button><button class="error-id-mode-card error-id-mode-card--jayden">300</button></div></section><section data-error-id-single hidden></section><section data-error-id-passage hidden></section><section data-error-id-bar hidden></section></div></body></html>'}));
await errorPage.goto('http://127.0.0.1:8633/error-test.html');
for (const file of ['error-identifier.css','error-identifier-indefinite.css']) await errorPage.addStyleTag({path:file});
await errorPage.evaluate(() => { window.EDMUND_LEARNING_PORTAL_CONTEXT = { getSession: () => ({user:{id:'qa-error'}}) }; });
for (const file of ['grammar-indefinite-pronouns-data.js','error-identifier-indefinite.js']) await errorPage.addScriptTag({path:file});
assert.equal(await errorPage.locator('.error-id-mode-card').count(),4);
assert.equal(await errorPage.locator('.error-id-mode-card').nth(2).innerText().then(text => text.includes('200 題')),true);
const cardPositions = await errorPage.locator('.error-id-mode-card').evaluateAll(cards => cards.map(card => ({x:card.offsetLeft,y:card.offsetTop})));
assert.equal(cardPositions[2].x, cardPositions[0].x);
assert(cardPositions[2].y > cardPositions[0].y);
assert(cardPositions[3].x > cardPositions[2].x);
await errorPage.locator('.error-id-mode-card--indefinite').click();
assert.equal(await errorPage.locator('[data-question] .eyebrow').innerText(),'第 1 / 200 題');
await errorPage.locator('[data-mark="tick"]').click();
assert((await errorPage.locator('[data-progress]').innerText()).startsWith('1 / 200'));
await errorPage.locator('[data-passage]').selectOption('10');
await errorPage.locator('[data-go="200"]').click();
assert.equal(await errorPage.locator('[data-question] .eyebrow').innerText(),'第 200 / 200 題');
assert(await errorPage.evaluate(() => JSON.parse(localStorage.getItem('edmund-error-indefinite-200-v1:qa-error')).answers['1'].mark === 'tick'));
await errorPage.setViewportSize({width:390,height:844});
assert(!(await errorPage.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Proofreading mobile horizontal overflow');
assert.deepEqual(errors, []);
await browser.close();
console.log('PASS: 68 guide points, 250 grammar exercises, 200 proofreading questions, card order, navigation, local save and mobile width.');
