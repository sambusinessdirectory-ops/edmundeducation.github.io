#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {validateCatalogue,compileRecord,audioQueue,audioIdentityPayload,normalise,SCHEMA_VERSION} from './schema.mjs';

export function auditDiversity(records){
 const flags=[],seen=new Map();
 for(const record of records)for(const [field,value] of [
  ['listening',record.listening?.en],['scene',record.scene?.promptEn||record.scene?.promptZh],
  ['contrast',record.contrast?.promptEn||record.contrast?.promptZh],['dialogue',record.dialogue?.promptEn||record.dialogue?.promptZh],
  ['writing',record.writing?.promptZh]
 ]){
  const key=`${field}:${normalise(value||'')}`;
  if(seen.has(key))flags.push({lessonId:record.id,path:field,message:`Exact reused task wording from ${seen.get(key)}; compare before release.`});else seen.set(key,record.id);
 }
 // This flags mechanical English name/number substitution; it is not linguistic approval.
 const skeletons=new Map();
 for(const record of records){
  const text=record.listening?.en||'';
  const skeleton=text.replace(/\b[A-Z][a-z]+\b/g,'NAME').replace(/\d+/g,'NUMBER');
  const key=normalise(skeleton);
  if(skeletons.has(key))flags.push({lessonId:record.id,path:'listening',message:`Possible name-only model variant of ${skeletons.get(key)}.`});else skeletons.set(key,record.id);
 }
 return flags;
}
export function buildArtifacts(records,{release=false,shardSize=50,displayStart=11}={}){
 if(!Number.isSafeInteger(displayStart)||displayStart<1)throw new Error('Use a positive first display number.');
 if(!Number.isSafeInteger(shardSize)||shardSize<1||shardSize>100)throw new Error('Use a shard size from 1 to 100 lessons.');
 const validation=validateCatalogue(records,{release});validation.warnings.push(...auditDiversity(records));
 if(validation.errors.length)return {validation};
 const sorted=[...records].sort((a,b)=>a.number-b.number),compiled=sorted.map((record,index)=>({...compileRecord(record),sourceNumber:record.number,number:displayStart+index}));
 const optionsCatalogue=compiled.map(lesson=>({id:lesson.id,senses:['phrase'],questions:Object.fromEntries(lesson.questions.map(q=>[q.id,{type:q.type,answers:q.answers,options:q.options||[],...(q.optionIds?{optionIds:q.optionIds}:{})}]))}));
 const patterns=Object.fromEntries(sorted.map(record=>[record.id,record.target.pattern]));
 const queue=sorted.flatMap(audioQueue).map(clip=>{
  const key=audioIdentityPayload(clip);
  // Match the approved Python generator's sorted-key JSON (including spaces).
  const serialized='{'+Object.keys(key).sort().map(name=>JSON.stringify(name)+': '+JSON.stringify(key[name])).join(', ')+'}';
  return {...clip,synthesisKey:createHash('sha256').update(serialized).digest('hex')};
 });
 const header='// Generated by tools/advanced-native-bulk/build.mjs. Do not edit by hand.\n';
 const serialized=value=>JSON.stringify(value,null,2).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
 const shards={},index=[];
 // Partition by immutable source ordinal, so appending later batches does not shift
 // already published lessons between content shards.
 const groups=new Map();
 for(const lesson of compiled){const group=Math.floor((lesson.sourceNumber-1)/shardSize);if(!groups.has(group))groups.set(group,[]);groups.get(group).push(lesson);}
 for(const [group,lessons] of groups){
  const body=header+`export default ${serialized(lessons)};\n`;
  const hash=createHash('sha256').update(body).digest('hex').slice(0,16);
  const filename=`advanced-content/${String(group+1).padStart(4,'0')}-${hash}.mjs`;
  shards[filename]=body;
  for(const lesson of lessons){
   const {id,number,sourceNumber,titleZh,titleEn,cardTitleLines,kind,summary,course,slug,heading,completionTitle}=lesson;
   index.push({id,number,sourceNumber,titleZh,titleEn,...(cardTitleLines?{cardTitleLines}:{}),kind,summary,course,slug,heading,completionTitle,
    // Retain exact grading keys for historical progress before content loads.
    // Prompt text also keeps the existing history detail view useful.
    questions:lesson.questions.map(q=>({id:q.id,type:q.type,prompt:q.prompt,answers:q.type==='open'?[]:q.answers})),
    advancedLazy:true,contentShard:`./${filename}`});
  }
 }
 const fullBytes=Buffer.byteLength(header+`export default ${serialized(compiled)};\n`);
 const indexBody=header+`export default ${serialized(index)};\n`;
 return {validation,files:{
  ...shards,
  'advanced-imported.generated.mjs':indexBody,
  'advanced-targets.generated.mjs':header+`export default ${serialized(patterns)};\n`,
  'assessment-catalogue.generated.json':JSON.stringify(optionsCatalogue,null,2)+'\n',
  'audio-queue.generated.json':JSON.stringify(queue,null,2)+'\n',
  'validation-report.generated.json':JSON.stringify({schemaVersion:SCHEMA_VERSION,releaseGate:release,lessons:sorted.length,questions:compiled.reduce((sum,l)=>sum+l.questions.length,0),audioRequests:queue.length,uniqueSynthesisKeys:new Set(queue.map(c=>c.synthesisKey)).size,contentShards:Object.keys(shards).length,fullContentBytes:fullBytes,initialIndexBytes:Buffer.byteLength(indexBody),...validation},null,2)+'\n'
 }};
}
function main(){
 const args=process.argv.slice(2),release=args.includes('--release'),check=args.includes('--check');
 let output=null;const inputs=[];
 for(let index=0;index<args.length;index++){
  if(args[index]==='--out-dir')output=args[++index];
  else if(!args[index].startsWith('--'))inputs.push(args[index]);
  else if(!['--release','--check'].includes(args[index]))throw new Error(`Unknown option ${args[index]}`);
 }
 if(!inputs.length||!output)throw new Error('Usage: node tools/advanced-native-bulk/build.mjs INPUT.json [...] --out-dir OUTPUT [--release] [--check]');
 const records=inputs.flatMap(file=>{
  const data=JSON.parse(fs.readFileSync(file,'utf8'));
  if(!Array.isArray(data)&&data.schemaVersion!==SCHEMA_VERSION)throw new Error(`Unsupported schema in ${file}`);
  return Array.isArray(data)?data:data.lessons;
 });
 const artifacts=buildArtifacts(records,{release});
 if(artifacts.validation.errors.length){process.stderr.write(JSON.stringify(artifacts.validation,null,2)+'\n');process.exitCode=1;return;}
 if(!check)fs.mkdirSync(output,{recursive:true});
 for(const [name,body] of Object.entries(artifacts.files)){
  const filename=path.join(output,name);
  if(check){if(!fs.existsSync(filename)||fs.readFileSync(filename,'utf8')!==body)throw new Error(`Generated output is stale: ${filename}`);}
  else{fs.mkdirSync(path.dirname(filename),{recursive:true});fs.writeFileSync(filename,body);}
 }
 console.log(`${records.length} lessons, ${records.length*6} questions, ${records.length*4} audio requests; ${artifacts.validation.warnings.length} review flags. ${release?'Release gate passed.':'Draft outputs; release reviews are not certified.'}`);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))main();
