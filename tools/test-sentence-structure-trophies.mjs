import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {sentenceTrophyState,sentenceTrophyCollection} from '../sentence-structure-trophies.mjs';
const manifest=JSON.parse(await readFile(new URL('../assets/sentence-structure/library/manifest.json',import.meta.url),'utf8'));
const lessons=manifest.lessons.map(({questionRefs,...l})=>({...l,questions:questionRefs.map(([id])=>({id}))}));
const lesson=lessons[3],ids=lesson.questions.map(q=>q.id);
const attempt=(n,extra={})=>({lessonId:lesson.id,status:n===50?'completed':'in_progress',correctCount:n,totalCount:50,result:{correctIds:ids.slice(0,n)},...extra});
assert.equal(sentenceTrophyState(lesson,[]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(49)]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(50)]).earned,true);
assert.equal(sentenceTrophyState(lesson,[attempt(50,{result:{}})]).earned,true,'Legacy complete counts retain their trophy');
assert.equal(sentenceTrophyState(lesson,[attempt(50,{result:{correctIds:[...ids.slice(0,49),ids[0]]}})]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(50,{result:{correctIds:[...ids.slice(0,49),'foreign-id']}})]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(50,{status:'in_progress'})]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(10,{status:'completed',totalCount:10})]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(25),attempt(25,{result:{correctIds:ids.slice(25)}})]).earned,false,'Do not combine separate partial attempts');
assert.equal(sentenceTrophyState(lesson,[attempt(50),attempt(1)]).earned,true,'A new practice attempt does not revoke an earned trophy');
assert.equal(sentenceTrophyState({...lesson,questions:[]},[attempt(50)]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(Infinity)]).earned,false);
assert.equal(sentenceTrophyState(lesson,[attempt(51)]).earned,false);
const all=lessons.map(l=>({lessonId:l.id,status:'completed',correctCount:50,totalCount:50}));
assert.equal(sentenceTrophyCollection(lessons,all).filter(x=>x.earned).length,345);
assert.equal(sentenceTrophyCollection(lessons,[]).filter(x=>x.earned).length,0);
console.log('Golden Horsey: exact 50-question completion, unique IDs, legacy records, no partial-attempt pooling, all 345 modules and empty-owner state passed.');
