import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {prepareTranslation} from './dse-reading-translations.mjs';
const root=new URL('../',import.meta.url);
const read=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
const data=await read('dse-reading-data/dse-2024-b2.json');
assert.equal(data.title,'Bad Science');
assert.equal(data.paragraphs.length,15);
assert.deepEqual(data.paragraphs.map(p=>p.number),Array.from({length:15},(_,i)=>i+1));
assert.match(data.paragraphs[11].text,/rhetorical slights of hand/,'Retain the supplied paper’s wording');
assert.match(data.paragraphs[14].text,/manage right now\.$/);
assert.deepEqual(data.questions.map(q=>q.number),Array.from({length:20},(_,i)=>i+43));
assert.equal(data.questions.reduce((sum,q)=>sum+(q.parts?.length||1),0),42);
const q=n=>data.questions.find(q=>q.number===n);
for(const [n,count] of [[43,4],[45,2],[46,2],[48,6],[51,5],[55,5],[61,5]])assert.equal(q(n).parts.length,count);
for(const n of [52,58])assert.deepEqual(q(n).options.map(o=>o.value),['A','B','C','D']);
for(const n of [43,51,55,61])assert.equal(q(n).tables[0].compact,true,'Answer columns must fit mobile screens');
assert.equal(q(55).tables[0].rows[1][1].text,'two (example)');
assert.equal(q(61).tables[0].rows[1][1].text,'A (example)');
assert.ok(!q(55).tables[0].rows[1][1].part && !q(61).tables[0].rows[1][1].part);
assert.equal(q(61).optionBank.length,7);
q(61).parts.forEach(p=>assert.deepEqual(p.options,['B','C','D','E','F','G']));
assert.ok((await readFile(new URL(q(61).figures[0].src,root))).length>10000);
const row=prepareTranslation(data,await read('tools/dse-reading-translations/dse-2024-b2.json'));
assert.equal(row.content.entries.filter(e=>/^paragraphs\/\d+\/text$/.test(e.path)).length,15);
assert.ok(data.questions.every(q=>!('answer' in q)));
const year=(await read('dse-reading-catalogue.json')).years.find(y=>y.year===2024);
assert.equal(year.sections.B2.id,data.id);
assert.equal(year.sections.A,null);assert.equal(year.sections.B1.id,'dse-2024-b1');
console.log('DSE 2024 B2: source-complete text, 20 questions, 42 answer fields, mobile tables, original speech bubbles and full translations verified.');
