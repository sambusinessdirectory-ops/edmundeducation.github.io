#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "flashcards-data-catalog.js");
const checkOnly = process.argv.includes("--check");

const lazyFiles = [
  ["flashcards-core-data.js", "20260916-lazy1"],
  ["flashcards-ielts-writing-advantage-cause-direct-data.js", "20260714-1"],
  ["flashcards-ielts-writing-express-4-31-data.js", "20260714-1"],
  ["flashcards-ielts-writing-opinions-3-38-express-32-43-data.js", "20260714-1"],
  ["flashcards-ielts-writing-opinions-39-82-data.js", "20260713-1"],
  ["flashcards-ielts-writing-task1-data.js", "20260729-2"],
  ["flashcards-dse-writing-part-a-data.js", "20260726-1"],
  ["flashcards-dse-listening-data.js", "20260726-2"],
  ["flashcards-dse-paper3-b2-2024-data.js", "20260725-1"],
  ["flashcards-dse-paper3-b2-2025-data.js", "20260725-1"],
  ...Array.from({ length: 8 }, (_, index) => [`flashcards-dse-speaking-${2012 + index}-data.js`, "20260713-1"]),
  ["flashcards-government-civics-book1-data.js", "20260808-1"],
  ["flashcards-government-civics-book2-data.js", "20260817-1"],
  ["flashcards-government-civics-book3-data.js", "20260920-1"],
  ["flashcards-government-concept-logic-book1-data.js", "20260817-1"],
  ["flashcards-hkfsd-concept-vocabulary-book1-data.js", "20260818-1"],
  ["flashcards-hkfsd-incident-reports-data.js", "20260818-1"],
  ["flashcards-hkpf-data.js", "20260715-1"],
  ["flashcards-business-concepts-book1-data.js", "20260816-1"],
  ["flashcards-sunny-s3-grammar-book-data.js", "20260908-1"]
];

const catalog = {};
for (const [file, version] of lazyFiles) {
  const source = readFileSync(path.join(root, file), "utf8");
  const sandbox = { window: {} };
  sandbox.window.window = sandbox.window;
  vm.runInNewContext(source, sandbox, { filename: file });
  const decks = sandbox.window.EDMUND_FLASHCARD_SEED || {};
  const titleMaps = Object.entries(sandbox.window)
    .filter(([key, value]) => key.endsWith("_TITLES") && value && typeof value === "object" && !Array.isArray(value))
    .map(([, value]) => value);
  for (const [deckId, cards] of Object.entries(decks)) {
    if (!Array.isArray(cards)) continue;
    const title = titleMaps.map(map => map[deckId]).find(Boolean) || "";
    catalog[deckId] = { u: `${file}?v=${version}`, c: cards.length, ...(title ? { t: title } : {}) };
  }
}

const sortedCatalog = Object.fromEntries(
  Object.entries(catalog).sort(([left], [right]) => left.localeCompare(right, "en"))
);
const generated = `/* Generated by tools/build-flashcard-lazy-startup.mjs. */\nwindow.EDMUND_FLASHCARD_DATA_CATALOG = Object.freeze(${JSON.stringify(sortedCatalog)});\n`;

if (checkOnly) {
  assert.equal(readFileSync(outputPath, "utf8"), generated, "Flashcard lazy-load catalog is stale");
} else {
  writeFileSync(outputPath, generated);
}

const html = readFileSync(path.join(root, "flashcards.html"), "utf8");
assert.ok(html.includes('data-flashcard-lazy-bundles'), "Flashcard content scripts must remain outside startup");
assert.ok(html.includes('flashcards-data-catalog.js?v=20260916-lazy1'), "Flashcard data catalog is not loaded at startup");
console.log(JSON.stringify({ decks: Object.keys(sortedCatalog).length, files: lazyFiles.length, checkOnly }));
