requireCondition(content?.system === "phrasal-verb", "Phrasal Verb public data is missing");
requireCondition(Array.isArray(content.lessons) && content.lessons.length === 329, `Expected 329 lessons, found ${content?.lessons?.length || 0}`);
const rows = valuesRows(content.lessons);
const generatedCountFunction = questionCountFunction(rows);

let baseSql = fs.readFileSync(baseSqlPath, "utf8");
baseSql = replaceFunction(baseSql, "_phrasal_verb_system_question_count", generatedCountFunction);
fs.writeFileSync(baseSqlPath, baseSql);

