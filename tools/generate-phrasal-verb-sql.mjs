import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(root, "phrasal-verb-system-data.js");
const baseSqlPath = path.join(root, "supabase-phrasal-verb-system.sql");
const migrationPath = path.join(root, "supabase-phrasal-verb-system-lessons-36-329.sql");

function requireCondition(condition, message) {
  if (!condition) throw new Error(message);
}

function readData() {
  const context = { window: {} };
  vm.runInNewContext(fs.readFileSync(dataPath, "utf8"), context, { filename: dataPath });
  return context.window.EDMUND_PHRASAL_VERB_SYSTEM_DATA;
}

function extractFunction(source, functionName) {
  const startMarker = `create or replace function public.${functionName}(`;
  const start = source.indexOf(startMarker);
  requireCondition(start >= 0, `Missing SQL function ${functionName}`);
  const end = source.indexOf("\n$$;", start);
  requireCondition(end >= 0, `Unterminated SQL function ${functionName}`);
  return source.slice(start, end + 4);
}

function replaceFunction(source, functionName, replacement) {
  const current = extractFunction(source, functionName);
  // Use a callback so PostgreSQL dollar quotes ("$$") are inserted verbatim;
  // String.prototype.replace otherwise treats "$$" as a replacement token.
  return source.replace(current, () => replacement.trim());
}

function valuesRows(lessons) {
  return lessons.map((lesson, index) => {
    const expectedId = `phrasal-verb-${String(index + 1).padStart(2, "0")}`;
    requireCondition(lesson?.id === expectedId, `Expected ${expectedId}, found ${lesson?.id || "(missing)"}`);
    requireCondition(Array.isArray(lesson.questions) && lesson.questions.length >= 1 && lesson.questions.length <= 999, `${expectedId} has an invalid question count`);
    return `    ('${lesson.id}'::text, ${lesson.questions.length}::integer)`;
  });
}

function questionCountFunction(rows) {
  return `create or replace function public._phrasal_verb_system_question_count(
  p_lesson_id text
)
returns integer
language sql
immutable
strict
parallel safe
set search_path = ''
as $$
  select lesson_row.question_count
  from (values
${rows.join(",\n")}
  ) as lesson_row(lesson_id, question_count)
  where lesson_row.lesson_id = p_lesson_id;
$$;`;
}

