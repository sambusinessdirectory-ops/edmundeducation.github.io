#!/usr/bin/env python3
"""Import six reviewed Grammar reading guides into canonical Markdown."""

from __future__ import annotations

import hashlib
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "course-materials/grammar/source"
DOWNLOADS = Path("/Users/sammak/Downloads")


def load(path: Path):
    spec = importlib.util.spec_from_file_location("grammar_import_shared", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(module)
    return module


shared = load(ROOT / "tools/import-grammar-seventeen-reading-guides.py")

# The Causative source uses shorter labels for the same six-step teaching model.
shared.LABEL_ALIASES.update({
    "① 意思": shared.STEP_LABELS[0],
    "② 英文例句": shared.STEP_LABELS[1],
    "③ 中文意思": shared.STEP_LABELS[2],
    "④ 為甚麼這樣寫": shared.STEP_LABELS[3],
    "⑤ 比較另一種寫法": shared.STEP_LABELS[4],
    "⑥ 限制或例外": shared.STEP_LABELS[5],
})

GUIDES = (
    ("causative-constructions", "CAU", 283, "Causative Constructions", "使役結構", "Causative Constructions — Complete Student Reading Guide (283 Lessons).docx"),
    ("cleft-pseudo-cleft-sentences", "CLF", 257, "Cleft & Pseudo-cleft Sentences", "分裂句與假分裂句", "Cleft_and_Pseudo_Cleft_Sentences_All_Forms_Complete_Student_Reading_Guide_v1.0.md"),
    ("transitivity-verb-valency", "VV", 272, "Transitivity & Verb Valency", "及物性與動詞配價", "Transitivity & Verb Valency — Complete Student Reading Guide (272 lessons).docx"),
    ("complements-complementation", "CMP", 348, "Complements & Complementation", "補語與補語結構", "Complements & Complementation — Complete Student Reading Guide.docx"),
    ("sentence-structure-types", "SS", 289, "Sentence Structure & Sentence Types", "句子結構與句子類型", "Sentence Structure & Sentence Types — Complete Student Reading Guide (289 lessons).docx"),
    ("inversion", "INV", 273, "Inversion", "倒裝句", "Inversion — Complete Student Reading Guide (273 Lessons).docx"),
)


def main() -> None:
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    for slug, prefix, count, _english, _chinese, filename in GUIDES:
        source = DOWNLOADS / filename
        if source.suffix.lower() == ".docx":
            body = shared.import_docx(source, prefix)
        else:
            body = shared.clean(source.read_text(encoding="utf-8")) + "\n"
        header = (
            "<!-- Generated by tools/import-grammar-six-reading-guides.py. -->\n"
            f"<!-- Source: {source.name}; SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()} -->\n\n"
        )
        content = header + body
        shared.validate(content, prefix, count, source)
        output = SOURCE_DIR / f"{slug}-student-reading-guide-{count}.md"
        output.write_text(content, encoding="utf-8")
        print(f"Imported {count:>3} rules: {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
