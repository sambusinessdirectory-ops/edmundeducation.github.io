#!/usr/bin/env python3
"""Build six source-complete reading-only Grammar modules."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "course-materials/grammar/source"
OUTPUT = ROOT / "grammar-six-reading-guides-data.js"
AUDIT_OUTPUT = ROOT / "course-materials/grammar/six-reading-guides-source-map.json"


def load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(module)
    return module


base = load(ROOT / "tools/build-grammar-four-reading-guides.py", "grammar_four_builder")
imports = load(ROOT / "tools/import-grammar-six-reading-guides.py", "grammar_six_imports")


def make_duplicate_notes_rule_specific(source: str, prefix: str) -> str:
    """Keep every source line and add the rule title only where captions repeat."""
    start = source.index("# PART III")
    end = source.index("# PART IV", start)
    area = source[start:end]
    matches = list(re.finditer(rf"^###\s+({prefix}\.\d{{2}}\.\d{{2}})\s+[—-]\s+(.+)$", area, re.M))
    records = []
    for index, match in enumerate(matches):
        stop = matches[index + 1].start() if index + 1 < len(matches) else len(area)
        block = area[match.end():stop]
        marker = re.search(r"^\*\*⑥ 最後看限制或例外\*\*\s*$", block, re.M)
        if not marker:
            continue
        note_end_match = re.search(r"^\s*##\s+", block[marker.end():], re.M)
        note_end = marker.end() + note_end_match.start() if note_end_match else len(block)
        note = "\n".join(base.step_lines(block[marker.end():note_end]))
        records.append({"title":match.group(2).strip(), "note":note, "insert":start + match.end() + marker.end()})
    counts = {}
    for record in records:
        counts[record["note"]] = counts.get(record["note"], 0) + 1
    output = source
    for record in reversed(records):
        if counts[record["note"]] > 1:
            at = record["insert"]
            output = output[:at] + f"\n\n「{record['title']}」：" + output[at:]
    return output


def main() -> None:
    guides, audits, global_ids = [], [], set()
    for slug, prefix, count, english, chinese, source_document in imports.GUIDES:
        source_path = SOURCE_DIR / f"{slug}-student-reading-guide-{count}.md"
        source = source_path.read_text(encoding="utf-8")
        if "而是" in source or "jayden" in source.lower():
            raise ValueError(f"Prohibited wording remains in {source_path}")
        config = {"slug":slug, "prefix":prefix, "count":count, "english":english, "chinese":chinese}
        render_source = make_duplicate_notes_rule_specific(source, prefix)
        guide_html, chapters, rules = base.build_guide(render_source, config)
        ids = re.findall(r'data-concept-number="([A-Z]+\.\d{2}\.\d{2})"', guide_html)
        if len(ids) != count or len(set(ids)) != count:
            raise ValueError(f"Generated card count drifted for {slug}")
        if global_ids.intersection(ids):
            raise ValueError(f"Cross-guide rule ID collision in {slug}")
        global_ids.update(ids)
        for part in ("PART IV", "PART V", "PART VI", "PART VII", "PART VIII", "PART IX", "PART X"):
            if part not in guide_html:
                raise ValueError(f"{part} missing from {slug}")
        if re.search(r"<(?:form|input|textarea|select|button)\b", guide_html, re.I):
            raise ValueError(f"Interactive assessment leaked into reading-only guide {slug}")
        guides.append({
            "slug":slug, "english":english, "chinese":chinese, "count":count,
            "practiceCount":0, "readingOnly":True, "html":guide_html, "chapters":chapters,
        })
        audits.append({
            "slug":slug, "source":str(source_path.relative_to(ROOT)), "sourceDocument":source_document,
            "canonicalSha256":hashlib.sha256(source.encode()).hexdigest(), "ruleCount":count,
            "tableCount":guide_html.count("<table>"), "readingOnly":True,
            "rules":[{"id":r["id"], "title":r["title"], "dialogueNote":"\n".join(r[base.STEP_LABELS[-1]])} for r in rules],
        })
    expected_total = sum(item[2] for item in imports.GUIDES)
    if len(global_ids) != expected_total:
        raise ValueError(f"Expected {expected_total:,} unique cards, found {len(global_ids)}")
    payload = (
        "// Generated by tools/build-grammar-six-reading-guides.py from six reviewed student guides.\n"
        "(() => {\n"
        f"  const incoming = {json.dumps(guides, ensure_ascii=False, separators=(',', ':'))};\n"
        "  const guides = Array.isArray(window.EDMUND_GRAMMAR_NEW_CURATIONS_DATA) ? [...window.EDMUND_GRAMMAR_NEW_CURATIONS_DATA] : [];\n"
        "  for (const guide of incoming) if (!guides.some((item) => item.slug === guide.slug)) guides.push(Object.freeze(guide));\n"
        "  window.EDMUND_GRAMMAR_NEW_CURATIONS_DATA = guides;\n"
        "  window.EDMUND_GRAMMAR_SIX_READING_GUIDES = Object.freeze({ guides: incoming });\n"
        "})();\n"
    )
    OUTPUT.write_text(payload, encoding="utf-8")
    AUDIT_OUTPUT.write_text(json.dumps({"guides":audits}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Built {expected_total:,} cards across six reading-only Grammar guides.")


if __name__ == "__main__":
    main()
