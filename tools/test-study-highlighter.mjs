import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {JSDOM} = require('./email-qa/node_modules/jsdom');
const {window} = new JSDOM('<main id="root"></main>', {url:'https://edmundeducation.com/junior-exam-prep.html'});
for (const key of ['document','Node','NodeFilter','MutationObserver','localStorage','location']) globalThis[key] = window[key];
globalThis.getSelection = () => window.getSelection();
globalThis.addEventListener = window.addEventListener.bind(window);
globalThis.confirm = () => true;
const paint = new Map();
globalThis.CSS = {highlights:{set:(key,value)=>paint.set(key,value),delete:key=>paint.delete(key)}};
globalThis.Highlight = class { constructor(...ranges) { this.ranges = ranges; } };
let owner = 'student-a';
globalThis.EDMUND_LEARNING_PORTAL_CONTEXT = {getSession:()=>({user:{id:owner}})};
const {juniorHighlightToolbar,mountJuniorHighlighter} = await import('../junior-text-highlighter.mjs');
const root = document.querySelector('#root');
root.innerHTML = juniorHighlightToolbar() + '<section class="passage" data-highlight-key="passage-1">We learned from the first mistake.</section>';
const tool = mountJuniorHighlighter(root,'.passage','exam',{scopeSelector:'.passage',scopeKey:node=>node.dataset.highlightKey});
root.querySelector('[data-junior-highlight-color="green"]').click();
function select(text) {
  const node = root.querySelector('.passage').firstChild;
  const start = node.data.indexOf(text);
  const range = document.createRange();
  range.setStart(node,start);range.setEnd(node,start+text.length);
  const selection = window.getSelection();selection.removeAllRanges();selection.addRange(range);
  root.dispatchEvent(new window.Event('keyup',{bubbles:true}));
}
const flush = () => new Promise(resolve=>setTimeout(resolve,20));
select('first mistake');
await flush();
assert.equal(paint.get('junior-exam-green')?.ranges[0].toString(),'first mistake');
assert.match(localStorage.getItem('edmund-study-highlights-v2:/junior-exam-prep.html:exam:student-a'),/first mistake/);
root.querySelector('.passage').outerHTML = '<section class="passage" data-highlight-key="passage-1">We learned from the first mistake.</section>';
await flush();
assert.equal(paint.get('junior-exam-green')?.ranges[0].toString(),'first mistake','mark survives a full exercise redraw');
owner = 'student-b';
window.dispatchEvent(new window.Event('edmund:learning-portal-session'));
await flush();
assert.equal(paint.has('junior-exam-green'),false,'account switch cannot show another student’s marks');
owner = 'student-a';
window.dispatchEvent(new window.Event('edmund:learning-portal-session'));
await flush();
assert.equal(paint.get('junior-exam-green')?.ranges[0].toString(),'first mistake','returning account restores marks');
root.querySelector('[data-junior-highlight-clear]').click();
await flush();
assert.equal(paint.has('junior-exam-green'),false);
assert.equal(JSON.parse(localStorage.getItem('edmund-study-highlights-v2:/junior-exam-prep.html:exam:student-a')).length,0);
console.log('Shared highlighter preserves marks across redraws and account switches; only Clear All removes them.');
