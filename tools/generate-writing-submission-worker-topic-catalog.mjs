import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { HOMEWORK_RESOURCE_CATALOG } from "../homework-resource-catalog.mjs";

const toolsDirectory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(toolsDirectory, "..");
const output = path.join(root, "workers/writing-submission/src/topic-catalog.js");

const topics = HOMEWORK_RESOURCE_CATALOG
  .filter((resource) => resource?.type === "fill-blanks")
  .map((resource) => ({
    id: resource.id,
    type: "fill-blanks",
    label: resource.label,
    detail: resource.detail || "Writing Practice",
    sectionKey: resource.sectionKey,
    questionPrompt: Array.isArray(resource.questionPrompt) ? resource.questionPrompt : [],
    questionImages: Array.isArray(resource.questionImages) ? resource.questionImages : []
  }));

if (!topics.length || topics.some((topic) => !topic.id || !topic.sectionKey)) {
  throw new Error("The canonical Writing Submission topic catalogue is incomplete.");
}

const source = `// Generated by tools/generate-writing-submission-worker-topic-catalog.mjs. Do not edit by hand.\n`
  + `export const WRITING_SUBMISSION_TOPIC_CATALOG = Object.freeze(${JSON.stringify(topics, null, 2)});\n`;
await writeFile(output, source, "utf8");
console.log(`Wrote ${topics.length} canonical Writing Submission topics to ${path.relative(root, output)}.`);
