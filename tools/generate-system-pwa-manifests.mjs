#!/usr/bin/env node

import assert from "node:assert/strict";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const args = new Set(process.argv.slice(2));
const check = args.has("--check");
assert.ok([...args].every((arg) => arg === "--check"), "usage: generate-system-pwa-manifests.mjs [--check]");
const protectedHtml = new Set(["schedule-system.html", "writing-submission.html"]);
const navSource = await readFile(new URL("shared-system-nav.js", root), "utf8");
const systemPattern = /\{ id: "([^"]+)", href: "([^"]+)", zh: "([^"]+)", en: "([^"]+)" \}/g;
const systems = Array.from(navSource.matchAll(systemPattern), ([, id, href, zh, en]) => ({ id, href, zh, en }));

assert.ok(systems.length >= 43, "shared system catalogue unexpectedly lost entries");
assert.equal(new Set(systems.map(({ id }) => id)).size, systems.length, "system ids must be unique");
assert.equal(new Set(systems.map(({ href }) => href)).size, systems.length, "system start pages must be unique");

const shortNames = Object.freeze({
  progress: "英文進度", flashcards: "Flashcards", writing: "寫作練習", "writing-submission": "Writing 交文",
  speaking: "Speaking 練習", listening: "聆聽練習", sentence: "句子結構", idioms: "英文慣用語",
  proverbs: "英文諺語", "phrasal-verbs": "動詞片語", "dse-paper3-analysis": "DSE 卷3分析",
  "ielts-reading-analysis": "IELTS 閱讀分析", schedule: "功課溫習安排", downloads: "教材下載",
  "video-class": "Edmund 錄影班", "parent-communication": "家長溝通", "common-expression-speaking": "常用語會話",
  "common-expression-written": "常用語寫作", "common-expression-rhetorical-speaking": "修辭常用語會話",
  "common-expression-rhetorical-writing": "修辭常用語寫作", "common-expression-professional-message": "商業訊息常用語",
  "common-expression-business-speaking": "商務會話常用語", quotes: "英文語錄", grammar: "英文語法",
  collocation: "英文配詞", "irregular-verb": "不規則動詞", "thematic-vocabulary": "主題生字",
  "part-of-speech": "詞性練習", synonyms: "同義詞", "error-identifier": "錯因分析",
  "learning-roadmap": "英文學習路線", spelling: "拼寫練習", "reading-logic": "閱讀題型邏輯",
  "translation-skills": "英譯中學習", "business-school": "商學院英文", "complex-questions": "英文複雜問句",
  "leisurely-reading": "英文導讀", "english-humour-speaking": "英文幽默會話",
  "english-humour-writing": "英文幽默寫作", "english-joke-collection": "英文笑話", "argument-learning": "論證學習",
  "fragmented-reading": "碎片閱讀", "precise-language": "精準措詞"
});
assert.deepEqual(Object.keys(shortNames).sort(), systems.map(({ id }) => id).sort(), "every app needs an intentional short name");
assert.equal(new Set(Object.values(shortNames)).size, systems.length, "installed app short names must be distinct");

const icons = [
  { src: "/assets/icons/icon-192x192.png", sizes: "192x192", type: "image/png", purpose: "any" },
  { src: "/assets/icons/edmundeducation-logo-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
  { src: "/assets/icons/icon-maskable-192x192.png", sizes: "192x192", type: "image/png", purpose: "maskable" },
  { src: "/assets/icons/icon-maskable-512x512.png", sizes: "512x512", type: "image/png", purpose: "maskable" }
];
const manifests = systems.map((system) => ({
  system,
  path: `pwa-manifests/${system.id}.webmanifest`,
  content: `${JSON.stringify({
    id: `/apps/${system.id}`,
    name: `${system.zh}｜EdmundEducation`,
    short_name: shortNames[system.id],
    description: `${system.zh}（${system.en}）EdmundEducation 學習系統。`,
    lang: "zh-Hant-HK", dir: "ltr", start_url: `/${system.href}?source=pwa`, scope: "/",
    display: "standalone", orientation: "any", background_color: "#f4f6fb", theme_color: "#20283d",
    categories: ["education", "productivity"], prefer_related_applications: false, icons
  }, null, 2)}\n`
}));
const catalogueContent = `// Generated by tools/generate-system-pwa-manifests.mjs.\nexport const EDMUND_PWA_APPS = Object.freeze(${JSON.stringify(systems.map((system) => ({
  ...system, name: `${system.zh}｜EdmundEducation`, shortName: shortNames[system.id],
  manifest: `/pwa-manifests/${system.id}.webmanifest`
})), null, 2)}.map(Object.freeze));\n`;

async function expectOrWrite(path, content) {
  const url = new URL(path, root);
  if (check) {
    assert.equal(await readFile(url, "utf8"), content, `${path} is stale; run the manifest generator`);
  } else {
    await writeFile(url, content, "utf8");
  }
}

if (!check) await mkdir(new URL("pwa-manifests/", root), { recursive: true });
for (const { system, path, content } of manifests) {
  await stat(new URL(system.href, root));
  await expectOrWrite(path, content);
  const htmlUrl = new URL(system.href, root);
  const html = await readFile(htmlUrl, "utf8");
  const expectedHref = `/pwa-manifests/${system.id}.webmanifest`;
  if (protectedHtml.has(system.href)) {
    if (check) assert.match(html, new RegExp(`<link rel="manifest" href="${expectedHref.replaceAll("/", "\\/")}">`), `${system.href}: protected page manifest link is stale`);
    continue;
  }
  const next = html.replace(/<link rel="manifest" href="[^"]+">/, `<link rel="manifest" href="${expectedHref}">`);
  assert.notEqual(next, html.includes(`href="${expectedHref}"`) ? `${html}__already_current__` : html, `${system.href}: missing manifest link`);
  if (check) assert.equal(html, next, `${system.href}: must link ${expectedHref}`);
  else if (next !== html) await writeFile(htmlUrl, next, "utf8");
}
await expectOrWrite("pwa-app-catalog.mjs", catalogueContent);

console.log(`${check ? "Verified" : "Generated"} ${systems.length} distinct system manifests and static page links${protectedHtml.size ? " (two protected page links are managed separately)" : ""}.`);
